#define GCN_TXT8_W 8
#define GCN_TXT8_H 16
#define GCN_TXT8_ADV 9

static inline uint8_t GCN_txt8_lit(char c) {
    if (c >= 'a' && c <= 'z') c = (char) (c - 32);
    if (c < 32) c = 32;
    if (c > 95) c = 95;   // clamp to '_' rather than space so weird chars show
    return (uint8_t) (c - 32);
}

// Draw one glyph at (px,py), scale N.  Always writes complete YUYV pairs.
// We render the 8-wide glyph in 4 pair-columns.  Neutral chroma 0x80.
static inline void GCN_txt8_glyph(u32* xfb32, u32 stride32, int px, int py, int scale,
                                   char ch, uint8_t fgY, uint8_t bgY) {
    const uint8_t* rows = GCN_TXT_FONT8[GCN_txt8_lit(ch)];
    const uint8_t cNeutral = 0x80;
    for (int r = 0; r < GCN_TXT8_H; ++r) {
        uint8_t bits = rows[r];
        for (int sy = 0; sy < scale; ++sy) {
            int y = py + r * scale + sy;
            if (y < 0 || y >= 480) continue;
            u32* row = xfb32 + (u32) y * stride32;
            int x = px;
            for (int pair = 0; pair < 4; ++pair) {
                if (x < 0) { x += 2 * scale; continue; }
                if (x + 2 * scale > (int) (stride32 * 2)) { x += 2 * scale; continue; }
                int col0 = pair * 2;
                int col1 = pair * 2 + 1;
                // sample the 1x1 font cell at the left edge of each on-screen column
                uint8_t y0 = (bits & (uint8_t) (1u << (7 - col0))) ? fgY : bgY;
                uint8_t y1 = (bits & (uint8_t) (1u << (7 - col1))) ? fgY : bgY;
                // For scaled columns, every pixel in the 2*scale-wide pair block
                // gets the same pair value.  This is a chunky upscale, not smooth,
                // but is fast and perfectly readable.
                for (int sx = 0; sx < scale; ++sx) {
                    int xx = x + pair * 2 * scale + sx * 2;
                    if (xx < 0 || xx + 1 >= (int) (stride32 * 2)) continue;
                    // big-endian 32-bit YUYV word = (Y0<<24)|(Cb<<16)|(Y1<<8)|Cr
                    row[xx / 2] = ((u32) y0 << 24) | ((u32) cNeutral << 16) |
                                  ((u32) y1 << 8)  | ((u32) cNeutral);
                }
            }
        }
    }
}

// Draw a string.  px/gy are in 1x1 screen pixels.  scale=1 gives 8x16 cells.
static inline void GCN_txt8_draw(u16* xfb, u32 stride, int px, int py, int scale,
                                  uint8_t fgY, uint8_t bgY, const char* s) {
    u32* xfb32 = (u32*) xfb;
    u32 stride32 = stride / 2;   // number of 32-bit YUYV pairs per row
    int cx = px;
    for (; s != NULL && *s != '\0'; ++s) {
        if (*s == '\n') { py += (GCN_TXT8_H + 1) * scale; cx = px; continue; }
        GCN_txt8_glyph(xfb32, stride32, cx, py, scale, *s, fgY, bgY);
        cx += GCN_TXT8_ADV * scale;
    }
}
