// ===[ GCN software text overlay — pair-aligned YUYV version ]===
// Renders readable ASCII into the XFB using COMPLETE YUYV pixel pairs.
//
// WHY THIS DESIGN:
//   The GameCube XFB is YUYV: each 32-bit word covers two pixels:
//     bytes [Y0, Cb, Y1, Cr]   (PPC big-endian)
//   The old overlay wrote individual 16-bit pixels, which corrupts the shared
//   chroma of adjacent pixels and produces unreadable/color-fringed text on TV.
//   This version always writes aligned 32-bit pairs, with neutral chroma (0x80),
//   so text is clean grayscale and genuinely readable.
//
//   Font is 8x16, uppercase ASCII 32..95, thick strokes so it survives CRT blur.
